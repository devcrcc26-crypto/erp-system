/**
 * Seeds one showcase project per project type not already in DEMO-001/002/003.
 */
export async function seedAllProjectTypes(ctx: PmSeedContext): Promise<void> {
  console.log('Seeding showcase projects for all project types...');

  const users = await seedDemoUsers(ctx);
  const seeded: string[] = [];

  for (const def of SHOWCASE_PROJECTS) {
    if (COVERED_TYPES.has(def.projectType)) {
      continue;
    }
    const result = await seedProjectBundle(ctx, def, users);
    seeded.push(`${result.projectCode} (${def.projectType})`);
  }

  console.log(`  Showcase project types seeded: ${seeded.length}`);
  for (const line of seeded) {
    console.log(`    ${line}`);
  }
}
